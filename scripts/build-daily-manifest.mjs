#!/usr/bin/env node
/**
 * Builds the archive manifest of every daily flower that has BOTH a sidecar
 * (`<date>.json`) and an app-loadable image (`<date>.jpg` or `<date>.png`)
 * under docs/daily/<region>/.
 *
 * Written to two places:
 *   - docs/daily/manifest.json   (served from GitHub Pages; refreshed by CI)
 *   - lib/data/dailyArchive.ts   (bundled into the app as a snapshot, so the
 *     archive fallback works even before the live manifest exists)
 *
 * Shape (compact on purpose, it ships in the bundle):
 *   {
 *     generatedAt: ISO string,
 *     regions: { [region]: [[date, ext, latin], ...] }   // ascending by date
 *   }
 *
 * Usage: node scripts/build-daily-manifest.mjs [--check]
 *   --check  exit 1 if the bundled snapshot is missing entries the live tree has
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DAILY_DIR = join(ROOT, "docs", "daily");
const LIVE_OUT = join(DAILY_DIR, "manifest.json");
const BUNDLED_OUT = join(ROOT, "lib", "data", "dailyArchive.ts");
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

export function buildManifest(dailyDir = DAILY_DIR) {
	const regions = {};
	const regionDirs = readdirSync(dailyDir, { withFileTypes: true })
		.filter((d) => d.isDirectory())
		.map((d) => d.name)
		.sort();
	for (const region of regionDirs) {
		const dir = join(dailyDir, region);
		const files = new Set(readdirSync(dir));
		const entries = [];
		for (const file of files) {
			if (!file.endsWith(".json")) continue;
			const date = file.slice(0, -5);
			if (!DATE_RE.test(date)) continue;
			const ext = files.has(`${date}.jpg`)
				? "jpg"
				: files.has(`${date}.png`)
					? "png"
					: null;
			if (!ext) continue;
			let latin = "";
			try {
				const meta = JSON.parse(readFileSync(join(dir, file), "utf8"));
				if (!meta?.common) continue;
				latin = typeof meta.latin === "string" ? meta.latin : "";
			} catch {
				continue;
			}
			entries.push([date, ext, latin]);
		}
		entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
		if (entries.length > 0) regions[region] = entries;
	}
	return { generatedAt: new Date().toISOString(), regions };
}

function countEntries(manifest) {
	return Object.values(manifest.regions).reduce((n, e) => n + e.length, 0);
}

if (import.meta.url === `file://${process.argv[1]}`) {
	if (!existsSync(DAILY_DIR)) {
		console.error(`No daily directory at ${DAILY_DIR}`);
		process.exit(1);
	}
	const manifest = buildManifest();
	if (process.argv.includes("--check")) {
		const src = readFileSync(BUNDLED_OUT, "utf8");
		const bundled = JSON.parse(
			src.slice(src.indexOf("} = {") + 4, src.lastIndexOf("};") + 1),
		);
		const live = countEntries(manifest);
		const snap = countEntries(bundled);
		console.log(`live=${live} bundled=${snap}`);
		process.exit(snap >= live ? 0 : 1);
	}
	const json = JSON.stringify(manifest);
	writeFileSync(LIVE_OUT, json);
	writeFileSync(
		BUNDLED_OUT,
		`// Generated by scripts/build-daily-manifest.mjs. Do not edit by hand.\n// biome-ignore-all format: generated data\nconst dailyArchive: {\n\tgeneratedAt: string;\n\tregions: Record<string, [string, "jpg" | "png", string][]>;\n} = ${json};\n\nexport default dailyArchive;\n`,
	);
	console.log(
		`Wrote ${countEntries(manifest)} archive entries across ${Object.keys(manifest.regions).length} regions (${json.length} bytes)`,
	);
}
